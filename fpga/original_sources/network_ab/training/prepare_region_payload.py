"""Reviewable bounded host payload for the explicit region-program ABI.

Does not access JTAG or the board, and does not bypass the production B1 image
validator. The matching modified RTL and boot image are mandatory dependencies.
"""
import argparse,importlib.util,json,shutil,zlib
from pathlib import Path
from .runtime import file_hash,write_json
from .region_detail_target import ROOT,RUN


def main():
    p=argparse.ArgumentParser();p.add_argument('--program',type=Path,required=True);p.add_argument('--rtl',type=Path,required=True);p.add_argument('--boot',type=Path);p.add_argument('--name',required=True);a=p.parse_args()
    m=json.loads((a.program/'program.json').read_text());coupled=json.loads((a.rtl/'result.json').read_text());bound=json.loads((a.rtl/'inputs.json').read_text())
    assert coupled['status'] in ('REAL_FETCH_ISSUER_HEADER_CORE_DMA_PREFIX_PASS','REAL_FETCH_ISSUER_HEADER_CORE_DMA_FRAME_PASS')
    assert bound['program_sha256']==file_hash(a.program/'program.json') and Path(bound['program']).resolve()==a.program.resolve()
    assert all(file_hash(path)==digest for path,digest in bound['compiled_hashes'].items())
    cm=json.loads((a.program/'coefficient_map.json').read_text());coeff=(a.program/'coefficients-padded.bin').read_bytes()
    assert cm['existing_header_windows'] and file_hash(a.program/'coefficients-padded.bin')==cm['sha256'] and len(coeff)==20480
    assert b''.join(int(w,16).to_bytes(8,'little') for w in (a.program/'load_words.hex').read_text().split())==coeff
    for op in cm['operators']:
        assert 1792<=op['weight_offset']<op['weight_offset']+op['weight_bytes']<=12608
        assert 12608<=op['bias_offset']<15040 and 15040<=op['multiplier_offset']<17472 and 17472<=op['relu_offset']<17600
    root=ROOT/'runs'/RUN/a.name;root.mkdir(exist_ok=False);payload=[]
    for meta in m['streams']+[dict(name='coefficients-padded',address=m['coefficient_address'],bytes=len(coeff),sha256=cm['sha256'],crc32=zlib.crc32(coeff))]:
        name=meta['name']+'.bin';src=a.program/name;raw=src.read_bytes();assert len(raw)==meta['bytes'] and file_hash(src)==meta['sha256'] and zlib.crc32(raw)==meta['crc32']
        address=meta['address'];assert 0x04000000<=address<address+len(raw)<=0x05000000
        shutil.copy2(src,root/name);payload.append(dict(file=name,cpu_address=0xE1000000+address-0x04000000,physical_address=address,bytes=len(raw),sha256=file_hash(root/name),crc32=zlib.crc32(raw)))
    assert all(x['physical_address']+x['bytes']<=y['physical_address'] or y['physical_address']+y['bytes']<=x['physical_address'] for i,x in enumerate(payload) for y in payload[i+1:])
    # Bind any CPU proof to the exact program, coefficients and generated bytes.
    # An earlier graph's successful boot is not evidence for this payload.
    original=ROOT.parent/'hw/efinity/prototypes/frame_execution/board_integration/boot_image.py';source=original.read_text()
    literal='COEFFICIENTS = 0xE1200000';assert source.count(literal)==1
    frozen=root/'boot_image_region.py';frozen.write_text(source.replace(literal,f"COEFFICIENTS = 0x{payload[-1]['cpu_address']:08X}"),encoding='utf-8')
    spec=importlib.util.spec_from_file_location('region_boot_image',frozen);module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module);firmware=module.write_image(root/'firmware')
    boot_evidence=None
    if a.boot:
        br=json.loads((a.boot/'result.json').read_text());bi=json.loads((a.boot/'inputs.json').read_text())
        assert br['status']=='REAL_VENDOR_CPU_JTAG_REGION_LOAD_FOURSTATE_PASS'
        assert br['inputs_sha256']==file_hash(a.boot/'inputs.json')
        assert Path(bi['program']).resolve()==a.program.resolve() and bi['program_sha256']==file_hash(a.program/'program.json')
        assert bi['coefficients_sha256']==cm['sha256'] and bi['actual_vendor_cpu'] and bi['actual_jtag_upload']
        assert all(file_hash(r['snapshot'])==r['sha256'] for r in bi['inputs'])
        assert bi['tb_sha256']==file_hash(a.boot/'tb_real_boot.sv')
        assert bi['firmware']==firmware and (a.boot/'boot_image_region.py').read_bytes()==frozen.read_bytes()
        images=list((root/'firmware').glob('EfxSapphireSoc*.bin'));assert images
        assert all(f.read_bytes()==(a.boot/'firmware'/f.name).read_bytes() for f in images)
        boot_evidence=dict(result=str(a.boot/'result.json'),sha256=file_hash(a.boot/'result.json'),
            actual_vendor_cpu=True,actual_jtag=True,ddr_phy=False,full_cnn=False)
    tag=0xC321
    mailbox=[dict(address=0xF9000F08,data=tag),dict(address=0xF9000F0C,data=payload[-1]['crc32']),dict(address=0xF9000F10,data=payload[0]['crc32']),
        dict(address=0xF9000F14,data=payload[1]['crc32']),dict(address=0xF9000F18,data=3),dict(address=0xF9000F00,data=0x434E4E31)]
    result=dict(status='REGION_OFFLINE_PAYLOAD_REVIEWABLE_NOT_BOARD_RELEASE',program=str(a.program),program_sha256=file_hash(a.program/'program.json'),
        actual_coupled_rtl_test=str(a.rtl/'result.json'),actual_coupled_rtl_test_sha256=file_hash(a.rtl/'result.json'),payloads=payload,mailbox=mailbox,
        firmware=firmware,firmware_original_sha256=file_hash(original),firmware_modified_source_sha256=file_hash(frozen),cpu_firmware_validated=boot_evidence is not None,boot_evidence=boot_evidence,
        board_fit=False,final_sta=False,uploaded=False,style_accepted=False,not_B1_weight_only=True,
        required_integration=['Matching descriptor bit schema and counters','Region DMA C32 decoding and datapath extent','C8/C16 residual support',
            'Matching boot coefficient address','Full-board resource placement and timing','Full-frame trained-coefficient numeric test and real board video'])
    write_json(root/'payload.json',result)
    boot_note='实际厂商CPU/JTAG已按同一程序和系数通过新地址载入、回读、CRC拒绝及复位测试；DDR仍为行为模型。' if boot_evidence else '固件新地址尚未经过真实CPU执行验证。'
    (root/'README.txt').write_text('区域风格研究包：未上板、未容量/时序放行。\n必须搭配 payload.json 绑定的 RTL、指令和固件，不能直接替换 B1 权重。\n文件范围和实际数值验证证据见 payload.json。\n'+boot_note+'\n',encoding='utf-8')
    print('REGION_PAYLOAD_PREPARED',sum(r['bytes'] for r in payload),hex(payload[-1]['cpu_address']),flush=True)


if __name__=='__main__':main()
