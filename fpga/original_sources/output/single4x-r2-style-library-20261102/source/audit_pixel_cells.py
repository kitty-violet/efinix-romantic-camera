"""Measure exact native 4x4 cell colours before/after video encoding."""
from pathlib import Path
import json,hashlib
import cv2
import numpy as np
from PIL import Image

D=Path(__file__).resolve().parents[1]
OUT=D/'revisions/film-pixel-r2';OUT.mkdir(parents=True,exist_ok=True)

def stats(a):
    h,w=a.shape[:2];assert (h,w)==(720,1280)
    z=a.reshape(h//4,4,w//4,4,3)
    spread=z.max((1,3)).astype(int)-z.min((1,3)).astype(int)
    return dict(total_cells=spread.shape[0]*spread.shape[1],unequal_cells=int((spread.max(2)>0).sum()),maximum_in_cell_channel_range=int(spread.max()),mean_in_cell_channel_range=float(spread.mean()))

def main():
    rows=[]
    for scene in ['indoor','outdoor','crowd','water']:
        r=json.loads((D/'review/native/PIXEL_R39'/f'{scene}.json').read_text('utf-8'))
        p=D/'review/stills/PIXEL_R39'/f'{scene}_076_new.png';a=np.array(Image.open(p).convert('RGB'))
        assert hashlib.sha256(a.tobytes()).hexdigest()==r['new_raw_sha256'][76]
        cap=cv2.VideoCapture(r['native_video']['path']);decoded=[]
        for i in range(77):
            ok,b=cap.read();assert ok
            if i in [0,38,76]:decoded.append(dict(frame=i,**stats(b)))
        cap.release()
        rows.append(dict(scene=scene,native_bin_png=stats(a),decoded_video_frames=decoded))
    report=dict(status='MEASURED_NOT_ASSUMED',records=rows,note='Raw PNG SHA matches the frame generated by delivered BIN; decoded video includes codec and YUV conversion.')
    (OUT/'pixel-cell-audit.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps(report,ensure_ascii=False,indent=2))

if __name__=='__main__':main()
