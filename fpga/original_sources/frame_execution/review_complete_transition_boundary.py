"""Review upstream adapter sharing separately from the controller transition.

Preserves the strict whole-cone rejection. Does not redefine it as a pass.
The original requirement of zero COMB4 anywhere up to every FF also covered
unchanged AXI adapter logic; that is broader than the localized A/B experiment.
"""
import json,sys
from pathlib import Path
from run_units import ROOT,HERE,sha
from complete_control_transition import audit_delta,BASE

def main():
    board=ROOT/'tmp/frame-execution/connected-board-complete-transition2'
    root=ROOT/'tmp/frame-execution/complete-transition-boundary2'
    assert not root.exists();audit_delta(board)
    report=board/'complete_transition_map_audit.json'
    a=json.loads(report.read_text())
    assert a['status']=='D_CONE_SHARED_CELL_REMAINS'
    assert a['map_sha256']==sha(board/'outflow/ti60f225_oob.map.v')
    assert a['next_state_luts']==25 and a['cone_primitives']=={'EFX_LUT4':88,'EFX_COMB4':1}
    assert len(a['shared_cells'])==1
    name,cell=next(iter(a['shared_cells'].items()))
    adapter='video_processing_pipeline/pipeline/fabric/cpu_width_adapter/'
    assert cell['params']=={'LUTMASK':"16'h1144",'MODE':'"LOGIC"'}
    assert {k:v for k,v in cell['pins'].items() if k not in ('O','P')}=={
        'I0':adapter+'wstate[2]','I1':adapter+'wstate[1]','I3':"1'b0"}
    affected=[int(b) for b,x in a['states'].items() if name in x['cone']]
    assert affected==[5,6],affected
    # Independent original mapped-D reference: retain all 17,504 test cases,
    # add faults on both upstream outputs for every APB_SETUP stimulus.
    source=ROOT/'tmp/board-test/check-accepted-tail-nextstate.py'
    code=source.read_text()
    def sub(old,new):
        nonlocal code
        assert code.count(old)==1,old
        code=code.replace(old,new)
    sub("net=ROOT/'tmp/frame-execution/connected-board-accepted-tail2/outflow/ti60f225_oob.map.v'",f'net=Path({str(board/"outflow/ti60f225_oob.map.v")!r})')
    sub("out=ROOT/'tmp/board-test/accepted-tail-nextstate1.json';assert not out.exists()",f'out=Path({str(root/"boolean_result.json")!r});assert not out.exists()')
    sub("assert sha(net)=='e105a7d585283c229f8d4061d8f57bb4ffd0e9c1f83f6b3cc60b2660941641b1'",f"assert sha(net)=={a['map_sha256']!r}")
    sub("cone=json.loads((ROOT/'tmp/board-test/accepted-tail-state-cones1.json').read_text())",f"cone=json.loads(Path({str(report)!r}).read_text());isolation_checks=0")
    sub("cone['states'][str(i)]['ff']['pins']['D']","cone['states'][str(i)]['ff']['D']")
    original="  count+=1\n"
    injected="""  if state==8:
   for fault in range(4):
    for j,sig in enumerate(UPSTREAM_OUTPUTS):env[sig]=(fault>>j)&1
    ev.cache_clear()
    forced=sum(ev(cone['states'][str(i)]['ff']['D'])<<i for i in range(10))
    assert forced==16,('APB_SETUP upstream sensitivity',trial,fault,forced)
    isolation_checks+=1
   for sig in UPSTREAM_OUTPUTS:del env[sig]
   ev.cache_clear()
  count+=1
"""
    sub(original,injected)
    sub("special=special,mismatches=bad[:20]","upstream_fault_isolation_checks=isolation_checks,special=special,mismatches=bad[:20]")
    root.mkdir()
    # This is a frozen test artifact generated by the reviewed adapter.
    driver=root/'mapped_d_test.py';driver.write_text(code)
    (root/'inputs.json').write_text(json.dumps(dict(board=str(board),board_inputs_sha256=sha(board/'inputs.json'),
        map_sha256=a['map_sha256'],strict_audit_sha256=sha(report),source_reference_sha256=sha(source),
        driver_sha256=sha(driver),reviewer_sha256=sha(__file__)),indent=2))
    exec(compile(code,str(driver),'exec'),{'__file__':str(driver),'UPSTREAM_OUTPUTS':[cell['pins']['O'],cell['pins']['P']]})
    b=json.loads((root/'boolean_result.json').read_text())
    assert b['mismatch_count']==0 and b['checks']==17504 and b['upstream_fault_isolation_checks']==512
    result=dict(status='COMPLETE_TRANSITION_LOCAL_STRUCTURE_AND_UPSTREAM_BOUNDARY_PASS',
        inputs_sha256=sha(root/'inputs.json'),map_sha256=a['map_sha256'],next_state_single_output_luts=25,
        whole_cone_comb4_count=1,unchanged_upstream_cell=cell,affected_state_bits=affected,
        original_strict_rejection_preserved=str(report),boolean_result_sha256=sha(root/'boolean_result.json'),
        rationale='Remaining COMB4 depends only on unchanged width-adapter write-state FFs and reaches only next-state bits5/6. Local next-state25LUT and APB_ACCESS/RESPONSE D cones contain no COMB4. 512 forced O/P tests cannot reproduce the APB_SETUP failure. Full mapped Boolean and following sequential tests still cover AXI write transitions.',
        scope='Local implementation A/B gate, not proof COMB4 is defective or board is fixed.',hardware_access=False,board_release=False)
    (root/'result.json').write_text(json.dumps(result,indent=2));print(result['status'])
if __name__=='__main__':main()
