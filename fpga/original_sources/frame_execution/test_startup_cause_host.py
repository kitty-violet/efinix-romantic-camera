"""Hardware-free decoder and freshness regressions."""
import unittest
from unittest.mock import patch
from read_startup_cause import MAGIC,SCAN_BITS,decode,cell_decode
from read_startup_cause_snapshot import fresh,SnapshotPending
def raw(sequence=0,valid=True,busy=False):
 header=MAGIC|(int(valid)<<32)|(int(busy)<<33)|(int(busy)<<35)|(5<<40)|(sequence<<56)
 return header<<2
class Transport:
 def __init__(self,values):self.values=iter(values);self.calls=[]
 def scan(self,s,b):
  self.calls.append((s,b));return next(self.values)
class Host(unittest.TestCase):
 def test_layout_and_real_vector(self):
  # Values from actual mapped probe, not generated by the decoder's oracle.
  v=raw(9)>>2;v|=0xc5e0ff0040207782<<896;v|=0xc5e0ff0040207782<<960
  v|=(1<<63|1<<62|3<<56|77<<32|0x103)<<768
  v|=(1<<63|3<<56|88<<32|0x100)<<832
  d=decode(v<<2);self.assertTrue(all(x['matches'] for x in d['cell_probes'].values()))
  self.assertEqual(d['startup_trace']['first_active']['seen_handshake_mask'],3)
  self.assertEqual(d['startup_trace']['first_unsupported_transition']['read_state'],3)
  self.assertEqual(d['startup_trace']['first_unsupported_transition']['preceding_live'],'00000100')
 def test_zero_or_incomplete_not_pass(self):
  for v in (0,0xc5a0ff0040207782,0xc5e07f0040207782):self.assertFalse(cell_decode(v)['matches'])
 def test_each_sample_bit_corruption(self):
  for i in range(40):self.assertFalse(cell_decode(0xc5e0ff0040207782^(1<<i))['matches'])
 def test_signature_length(self):
  for v in (True,-1,1<<SCAN_BITS,raw()^(1<<42),raw()^4):
   with self.assertRaises(ValueError):decode(v)
 def test_fresh_wrap(self):
  t=Transport([raw(255),raw(255),raw(0)]);h=[]
  self.assertEqual(fresh(t,h,lambda:None)['sequence'],0)
  self.assertEqual(t.calls,[(3,1026),(2,1026),(3,1026)])
 def test_stale_rejected(self):
  t=Transport([raw(3)]*10)
  with self.assertRaises(SnapshotPending):fresh(t,[],lambda:None)
 def test_busy_rejected_without_request(self):
  t=Transport([raw(4,busy=True)]*9)
  with self.assertRaises(SnapshotPending):fresh(t,[],lambda:None)
  self.assertTrue(all(x[0]==3 for x in t.calls))
 def test_status_reader_uses_ofp5(self):
  import read_startup_cause_status as reader
  from test_command_progress_status import Transport as Bus,Tests
  self.assertEqual(reader.fresh.__module__,'read_startup_cause_snapshot')
  out=Tests().output()
  with patch.object(reader,'fresh',side_effect=Tests().snapshots()):reader.inspect(Bus(),out,lambda:None)
  self.assertEqual(out['status'],'OFP5_AND_STABLE_STATUS_READ_COMPLETE_NOT_BOARD_PASS')
  self.assertEqual(out['transactions'],15)
 def test_status_timeout_preserves_snapshot(self):
  import read_startup_cause_status as reader
  from test_command_progress_status import Transport as Bus,Tests
  out=Tests().output()
  with patch.object(reader,'fresh',return_value={'levels':{'control_reset':False},'format':'OFP5'}):
   with self.assertRaises(TimeoutError):reader.inspect(Bus(True),out,lambda:None)
  self.assertEqual(len(out['snapshots']),2)
if __name__=='__main__':unittest.main()
