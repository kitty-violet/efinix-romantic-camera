"""Retain only authored CNN RAM locations from the prior passing route.

RAM primitives consume a full tile, so this does not sacrifice the LUT/FF
packing that would be lost by assigning individual unpaired FFs. No protected
DDR cells or autogenerated LUT names are assigned across changed netlists.
"""
import collections
import json
import re
from pathlib import Path
from run_units import ROOT, EF, sha

PREFIX = 'video_processing_pipeline/pipeline/cnn/'


def memory_cells(net):
    text = re.sub(r'/\*.*?\*/|//[^\n]*', '', Path(net).read_text(), flags=re.S)
    cells = {name: kind for kind, name in re.findall(
        r'^\s*(EFX_(?:DP)?RAM10)\s+\\(\S+)\s*\(', text, re.M)
        if name.startswith(PREFIX)}
    params = {name: {} for name in cells}
    for name, key, value in re.findall(r'defparam\s+\\(\S+)\s*\.(\w+)\s*=\s*([^;]+);', text):
        if name in params:
            params[name][key] = re.sub(r'\s+', '', value)
    assert cells and all(params.values())
    return cells, params


def generate(root, reference):
    root, reference = Path(root).resolve(), Path(reference).resolve()
    assert root.is_relative_to(ROOT/'tmp') and reference.is_relative_to(ROOT/'tmp')
    from audit_canonical_multiseed import audit
    prior = audit(reference)
    assert prior['current_timing_pass'], 'Reference must pass original-constraint STA'
    old = Path(prior['physical'])
    old_net, new_net = old/'outflow/ti60f225_oob.map.v', root/'outflow/ti60f225_oob.map.v'
    before, before_params = memory_cells(old_net)
    after, after_params = memory_cells(new_net)
    assert before == after and before_params == after_params, 'CNN RAM primitives/parameters changed'
    assert collections.Counter(after.values()) == {'EFX_DPRAM10': 84, 'EFX_RAM10': 29}
    placement = old/'outflow/ti60f225_oob.out.placeloc'
    locations = {}
    for line in placement.read_text().splitlines():
        words = line.split()
        if len(words) == 4 and words[0] in after:
            assert words[0] not in locations
            locations[words[0]] = tuple(map(int, words[1:]))
    assert set(locations) == set(after)
    assert all(pos[2] == 0 for pos in locations.values())
    assert len(set(locations.values())) == len(locations)
    assignment = root/'fixed_dsp.placeloc'
    existing = assignment.read_text()
    assigned = {w[0]: tuple(map(int, w[1:])) for line in existing.splitlines()
                if len(w := line.split()) == 4 and not line.startswith('#')}
    assert not set(assigned).intersection(locations)
    assert not {p[:2] for p in assigned.values()}.intersection(p[:2] for p in locations.values())
    settings = root/'efx_pnr_settings.ini'
    assert 'loc_assignment = fixed_dsp.placeloc' in settings.read_text()
    docs = {name: sha(EF/'doc/topics'/name) for name in
            ('loc-assignment-file.html', 'loc-primitives.html', 'loc-rules.html')}
    assignment.write_text(existing + '# Unchanged named CNN RAM only; no FF/LUT pinning.\n' +
                          ''.join(f'{name} {x} {y} {sub}\n' for name, (x,y,sub) in sorted(locations.items())))
    result = dict(status='CNN_RAM_REFERENCE_ASSIGNMENTS_PREPARED_NOT_TIMING_PASS',
                  reference_canonical=str(reference), reference_physical=str(old),
                  reference_map_sha256=sha(old_net), candidate_map_sha256=sha(new_net),
                  reference_canonical_result_sha256=sha(reference/'result.json'),
                  reference_placement_sha256=sha(placement),
                  unchanged_memory_primitives=dict(collections.Counter(after.values())),
                  assignments={n:list(p) for n,p in locations.items()},
                  assignments_sha256=sha(assignment), official_docs=docs,
                  generator_sha256=sha(__file__), board_release=False)
    (root/'cnn_ram_placement.json').write_text(json.dumps(result, indent=2))
    (root/'cnn_ram_generator.py').write_bytes(Path(__file__).read_bytes())
    return result


def verify_placed(root):
    root=Path(root).resolve();proof=json.loads((root/'cnn_ram_placement.json').read_text())
    old=Path(proof['reference_physical']);canonical=Path(proof['reference_canonical'])
    assert sha(canonical/'result.json')==proof['reference_canonical_result_sha256']
    assert sha(old/'outflow/ti60f225_oob.out.placeloc')==proof['reference_placement_sha256']
    assert sha(old/'outflow/ti60f225_oob.map.v')==proof['reference_map_sha256']
    assert sha(root/'outflow/ti60f225_oob.map.v')==proof['candidate_map_sha256']
    assert memory_cells(old/'outflow/ti60f225_oob.map.v')==memory_cells(root/'outflow/ti60f225_oob.map.v')
    assert sha(root/'fixed_dsp.placeloc')==proof['assignments_sha256']
    locations={w[0]:list(map(int,w[1:])) for line in (root/'outflow/ti60f225_oob.out.placeloc').read_text().splitlines()
               if len(w:=line.split())==4 and not line.startswith('#')}
    for name,expected in proof['assignments'].items():
        assert locations.get(name)==expected, (name,expected,locations.get(name))
    return dict(status='CNN_RAM_113_PHYSICAL_LOCATIONS_MATCH',count=len(proof['assignments']),
                placement_sha256=sha(root/'outflow/ti60f225_oob.out.placeloc'),board_release=False)
